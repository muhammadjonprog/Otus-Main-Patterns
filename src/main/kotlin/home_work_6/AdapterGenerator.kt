package home_work_6

import kotlin.reflect.KClass
import kotlin.reflect.full.declaredFunctions

object AdapterGenerator {
    fun generateAdapterCode(iface: KClass<*>): String {
        val packageName = "autogenerated"
        val className = iface.simpleName + "Adapter"
        val builder = StringBuilder()

        builder.appendLine("package $packageName\n")
        builder.appendLine("class $className(private val obj: Any) : ${iface.qualifiedName} {")

        iface.declaredFunctions.forEach { func ->
            val returnType = func.returnType.toString().substringAfterLast(".")
            val name = func.name
            val params = func.parameters.filter { it.kind.name == "VALUE" }

            val paramDecl = params.joinToString(", ") { "${it.name}: ${it.type}" }
            val paramNames = params.joinToString(", ") { it.name ?: "arg" }

            builder.appendLine("    override fun $name($paramDecl): $returnType {")
            when {
                name.startsWith("get") -> {
                    builder.appendLine("        return IoC.resolve(\"${iface.qualifiedName}:${name.drop(3).lowercase()}.get\", obj)")
                }
                name.startsWith("set") && returnType == "Unit" -> {
                    builder.appendLine("        IoC.resolve<ICommand>(\"${iface.qualifiedName}:${name.drop(3).lowercase()}.set\", obj, $paramNames).execute()")
                }
                returnType == "Unit" -> {
                    builder.appendLine("        IoC.resolve<ICommand>(\"${iface.qualifiedName}:${name}\", obj, $paramNames).execute()")
                }
                else -> {
                    builder.appendLine("        return IoC.resolve(\"${iface.qualifiedName}:${name}\", obj, $paramNames)")
                }
            }
            builder.appendLine("    }")
        }

        builder.appendLine("}")
        return builder.toString()
    }
}
